#!/usr/bin/env python3
"""Проверка досягаемости целей для прогнозов ВСУ (скилл russia-ukraine-osint).

Обязательный шаг критик-пасса класса «прогноз/аналитическая модель»:
пересчитать досягаемость целей скриптом, а не на глаз.

Использование:
  python3 verify_distances.py                 # дефолтные цели (05.08.2026)
  python3 verify_distances.py "Кинеф:59.45,32.02" "Оленья:68.15,33.3"

Считает гаверсинусное расстояние от двух линий запуска:
  север (Сумы/Харьков, 50.5N 35E) и юг (фронт Запорожье, 47.5N 36.5E).
Сравнивает с дальностью FP-1 (~3400 км, модификация мая 2026):
  ДА  (<2800), ГРАНЬ (2800–3400), ВНЕ (>3400 — только заброска «Паутина»).

Замеры-эталоны (проверено 05.08.2026, критик снял ошибки черновика):
  Оленья 1965–2305 (НЕ 1500–1700!), Североморск 2070–2405,
  Энгельс ~785–825 (НЕ ~600), Самотлор ~2790–2940 (ГРАНЬ),
  Ангарск 4587–4670 (ВНЕ), Белая 4505–4589 (ВНЕ перелётом),
  Украинка 6086–6218 (ВНЕ), Ухта(прец.) 1827–2073, Омск(прец.) 2598–2664.
"""
import math
import sys

FP1 = 3400.0
P_N = (50.5, 35.0)   # северная линия запуска: Сумы/Харьковская граница
P_S = (47.5, 36.5)   # южная линия запуска: фронт Запорожье

DEFAULT_TARGETS = {
    "Энгельс": (51.48, 46.12),
    "Дягилево (Рязань)": (54.64, 39.57),
    "Иваново-Северный": (57.0, 40.95),
    "Шайковка (Калуга)": (54.2, 35.2),
    "Моздок": (43.74, 44.65),
    "Оленья": (68.15, 33.3),
    "Североморск": (69.08, 33.42),
    "Усть-Луга": (59.68, 28.3),
    "Приморск": (60.37, 28.61),
    "СПб": (59.94, 30.3),
    "Кириши (Кинеф)": (59.45, 32.02),
    "Новороссийск": (44.72, 37.77),
    "Геленджик": (44.56, 38.08),
    "Крымский мост": (45.3, 36.5),
    "Самотлор (Нижневартовск)": (60.94, 76.55),
    "Ангарск": (52.54, 103.9),
    "Белая (Иркутская)": (53.0, 102.9),
    "Украинка (Амурская)": (51.17, 128.4),
    "Ухта (прецедент)": (63.57, 53.68),
    "Омск (прецедент)": (55.0, 73.4),
}


def haversine(a, b):
    lat1, lon1 = map(math.radians, a)
    lat2, lon2 = map(math.radians, b)
    d = (math.sin((lat2 - lat1) / 2) ** 2
         + math.cos(lat1) * math.cos(lat2) * math.sin((lon2 - lon1) / 2) ** 2)
    return 2 * 6371 * math.asin(math.sqrt(d))


def flag(d):
    if d < 2800:
        return "ДА"
    if d <= FP1:
        return "ГРАНЬ"
    return "ВНЕ"


def main():
    targets = dict(DEFAULT_TARGETS)
    for arg in sys.argv[1:]:
        name, _, coords = arg.partition(":")
        try:
            lat, lon = map(float, coords.split(","))
        except ValueError:
            print(f"Неправильный формат '{arg}' — нужно 'Имя:lat,lon'")
            return 1
        targets[name] = (lat, lon)

    print(f"{'Цель':<26}{'от С (Сум)':>12}{'от Ю (фронт)':>13}  флаг")
    print("-" * 62)
    for name, c in sorted(targets.items(), key=lambda kv: min(
            haversine(P_N, kv[1]), haversine(P_S, kv[1]))):
        dN, dS = haversine(P_N, c), haversine(P_S, c)
        d = min(dN, dS)
        print(f"{name:<26}{dN:>9.0f} км{dS:>10.0f} км  {flag(d)}")
    print("-" * 62)
    print("ДА: перелёт возможен; ГРАНЬ: у предела FP-1 (3400 км);")
    print("ВНЕ: только заброска по методу «Паутины» (контейнеры на фурах).")


if __name__ == "__main__":
    sys.exit(main())
